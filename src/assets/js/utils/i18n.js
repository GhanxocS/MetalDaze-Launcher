let currentLang = 'es';

function t(key) {
    return (dict[currentLang] && dict[currentLang][key]) ?? (dict.es[key] ?? key);
}

/**
 * Recorre el DOM aplicando traducciones:
 *   data-i18n="key"             → textContent = t(key)
 *   data-i18n-html="key"        → innerHTML = t(key)  (solo para bloques
 *                                  de confianza propia, como la licencia)
 *   data-i18n-placeholder="key" → placeholder = t(key)
 *   data-i18n-aria-label="key"  → aria-label = t(key)
 */
function applyTranslations(lang) {
    currentLang = dict[lang] ? lang : 'es';
    document.documentElement.lang = currentLang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });
}

export { t, applyTranslations, currentLang };
